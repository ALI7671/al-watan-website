/*
 * Regenerates the server-rendered SEO content on public/signs.html from public/signs.json:
 *   - the intro paragraph + full sign index (real HTML, not JS-injected)
 *   - the ItemList/ImageObject JSON-LD block
 *
 * Both blocks live between HTML comment markers in signs.html and are fully
 * replaced on every run, so this script is safe to re-run whenever signs.json
 * changes (new signs added, names/meanings edited, etc).
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PUBLIC_DIR = path.join(ROOT, 'public');
const SIGNS_JSON_PATH = path.join(PUBLIC_DIR, 'signs.json');
const SIGNS_HTML_PATH = path.join(PUBLIC_DIR, 'signs.html');

const SITE_ORIGIN = 'https://www.alwatandrivingschool.com';

const CATEGORY_ORDER = ['تحذيرية', 'منع وتقييد', 'إلزامية', 'إرشادية', 'أولوية', 'ضوئية وحواجز', 'علامات أرضية'];

function escapeHTML(str) {
  return String(str ?? '').replace(/[&<>"']/g, (c) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  }[c]));
}

function signId(sign) {
  return `sign-${sign.file.replace(/\.[a-z0-9]+$/i, '')}`;
}

function buildIntroHTML(signs) {
  const examples = CATEGORY_ORDER
    .map((cat) => signs.find((s) => s.category === cat))
    .filter(Boolean)
    .map((s) => s.name);

  const introParagraph = `
      <p class="signs-intro-text">
        دليل شامل لإشارات المرور الفلسطينية مع شرح معنى كل إشارة. يضم هذا الدليل ${signs.length} إشارة مرورية
        معتمدة في فلسطين، موزّعة على فئات رئيسية: ${CATEGORY_ORDER.map(escapeHTML).join('، ')}. يشرح كل قسم معنى
        الإشارة بدقة لمساعدة طلاب مدرسة الوطن على فهم الشواخص المرورية والاستعداد للاختبار النظري والقيادة الآمنة
        على الطرق الفلسطينية. من أبرز الإشارات في الدليل: ${examples.map(escapeHTML).join('، ')}، وغيرها الكثير
        في الفهرس أدناه.
      </p>`;

  const indexItems = signs
    .map((s) => `        <li><a href="#${signId(s)}">${escapeHTML(s.name)}</a></li>`)
    .join('\n');

  const index = `
      <details class="signs-index">
        <summary>فهرس كل الإشارات (${signs.length} إشارة)</summary>
        <ul class="signs-index-list">
${indexItems}
        </ul>
      </details>`;

  return `${introParagraph}\n${index}`;
}

function buildJsonLd(signs) {
  const itemListElement = signs.map((s, i) => ({
    '@type': 'ListItem',
    position: i + 1,
    item: {
      '@type': 'ImageObject',
      name: s.name,
      description: s.meaning || s.name,
      contentUrl: `${SITE_ORIGIN}/images/${s.file}`,
      thumbnailUrl: `${SITE_ORIGIN}/images/${s.file}`,
      url: `${SITE_ORIGIN}/signs.html#${signId(s)}`,
      representativeOfPage: false,
    },
  }));

  const jsonLd = {
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    name: 'دليل إشارات المرور الفلسطينية',
    description: 'قائمة شاملة لإشارات المرور الفلسطينية مع شرح معنى كل إشارة',
    numberOfItems: signs.length,
    itemListElement,
  };

  return `<script type="application/ld+json">\n${JSON.stringify(jsonLd, null, 2)}\n</script>`;
}

function replaceBetweenMarkers(html, startMarker, endMarker, content) {
  const startIdx = html.indexOf(startMarker);
  const endIdx = html.indexOf(endMarker);
  if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
    throw new Error(`Markers not found or out of order: ${startMarker} / ${endMarker}`);
  }
  const before = html.slice(0, startIdx + startMarker.length);
  const after = html.slice(endIdx);
  return `${before}\n${content}\n    ${after}`;
}

function main() {
  const { signs } = JSON.parse(fs.readFileSync(SIGNS_JSON_PATH, 'utf8'));
  let html = fs.readFileSync(SIGNS_HTML_PATH, 'utf8');

  html = replaceBetweenMarkers(
    html,
    '<!-- SEO-SIGNS-INTRO:START (auto-generated by scripts/generate-signs-seo.js from signs.json — do not hand-edit) -->',
    '<!-- SEO-SIGNS-INTRO:END -->',
    buildIntroHTML(signs)
  );

  html = replaceBetweenMarkers(
    html,
    '<!-- SEO-SIGNS-JSONLD:START (auto-generated by scripts/generate-signs-seo.js from signs.json — do not hand-edit) -->',
    '<!-- SEO-SIGNS-JSONLD:END -->',
    buildJsonLd(signs)
  );

  fs.writeFileSync(SIGNS_HTML_PATH, html);
  console.log(`signs.html updated: intro + index (${signs.length} signs) + JSON-LD regenerated.`);
}

main();
